/**
 * Deterministic PRNG (mulberry32) - menu generation must never use
 * Math.random() directly, so the same seed + inputs always produce the
 * same menu (reproducible tests, reproducible debugging).
 */
export function mulberry32(seed: number): () => number {
  let a = seed;
  return function random() {
    a |= 0;
    a = (a + 0x6d2b79f5) | 0;
    let t = Math.imul(a ^ (a >>> 15), 1 | a);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}
